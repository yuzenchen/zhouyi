def build_seed_documents() -> list[dict]:
    """合併 trigrams.py 的卦名/索引 與本檔的卦辭、象辭、爻辭,產出可寫入 MongoDB 的 documents。"""
    docs = []
    for (inner, outer), meta in HEXAGRAM_LOOKUP.items():
        seq = meta["sequence"]
        seed = SEED_DATA.get(seq, {})
        lines_raw = LINES_DATA.get(seq, [])
        lines = [
            {"position": i + 1, "text_zh": zh, "text_en": en}
            for i, (zh, en) in enumerate(lines_raw)
        ]
        docs.append({
            "sequence": seq,
            "inner": inner,
            "outer": outer,
            "name_zh": meta["name_zh"],
            "name_en": meta["name_en"],
            "judgment_zh": seed.get("judgment_zh", ""),
            "judgment_en": seed.get("judgment_en", ""),
            "image_zh": seed.get("image_zh", ""),
            "image_en": seed.get("image_en", ""),
            "lines": lines,
        })
    docs.sort(key=lambda d: d["sequence"])
    return docs
